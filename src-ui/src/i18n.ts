export type I18nContextType = {
  lang: Lang
  t: (key: string) => string
  tArr: (key: string) => string[]
  switchLang: (lang: Lang) => void
}

export const I18nContext = createContext<I18nContextType>({
  lang: 'th',
  t: (k) => k,
  tArr: () => [],
  switchLang: () => {},
})

export function useI18nState() {
  const [lang, setLang] = useState<Lang>(() => (localStorage.getItem('lang') as Lang) || 'th')

  const t = useCallback((key: string): string => {
    const val = (I18N[lang] || I18N.th)[key] ?? (I18N.th as Record<string, unknown>)[key] ?? key
    if (Array.isArray(val)) return (val as string[]).join(',')
    return val as string
  }, [lang])

  const tArr = useCallback((key: string): string[] => {
    const val = (I18N[lang] || I18N.th)[key] ?? (I18N.th as Record<string, unknown>)[key]
    if (Array.isArray(val)) return val as string[]
    return []
  }, [lang])

  const switchLang = useCallback((newLang: Lang) => {
    localStorage.setItem('lang', newLang)
    document.documentElement.lang = newLang === 'zh' ? 'zh-CN' : newLang
    document.body.className = newLang === 'zh' ? 'lang-zh' : ''
    setLang(newLang)
  }, [])

  return { lang, t, tArr, switchLang }
}

export function useI18n() {
  return useContext(I18nContext)
}
